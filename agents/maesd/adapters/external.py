class ExternalBackendNotConfigured(RuntimeError):
    pass


class ExternalBackendExecutionError(RuntimeError):
    pass


class ExternalProGen2Adapter(SequenceGenerationBackend):
    """Run a real ProGen2-compatible command line and parse generated sequences."""

    def generate(self, request: GenerationRequest) -> List[DesignCandidate]:
        run_dir = Path(tempfile.mkdtemp(prefix="progen2_gen_"))
        prompt_path = run_dir / "prompt.txt"
        prompt_path.write_text(request.constraints.original_prompt, encoding="utf-8")
        placeholders = {
            "prompt_path": str(prompt_path),
            "prompt": request.constraints.original_prompt,
            "output_dir": str(run_dir),
            "population_size": str(request.population_size),
            "target_length": str(request.constraints.target_length),
            "python_bin": str(self.config.extra.get("python_bin", "python")),
            "script_path": str(self.config.extra.get("script_path", "")),
            "executable": str(self.config.executable or ""),
            "seed": str(request.seed),
        }
        command = self._build_command(placeholders)
        self._run_command(command)
        candidates = list(run_dir.glob("*.fa")) + list(run_dir.glob("*.fasta")) + list(run_dir.glob("*.json"))
        if not candidates:
            raise ExternalBackendExecutionError(f"ProGen2 command completed but no output was found under {run_dir}")
        sequences = self._parse_sequences(candidates[0])
        if not sequences:
            raise ExternalBackendExecutionError(f"No sequences could be parsed from {candidates[0]}")
        return [
            DesignCandidate(
                sequence=sequence,
                origin="progen2-cli",
                iteration=0,
                notes=[f"Generated by external ProGen2 command: {' '.join(command)}"],
                metadata={"backend": self.name, "provider": self.config.provider, "output_dir": str(run_dir)},
            )
            for sequence in sequences[: request.population_size]
        ]

    def _build_command(self, placeholders: Dict[str, str]) -> List[str]:
        template = self.config.extra.get("command")
        if template:
            return _render_command(template, placeholders)
        script_path = placeholders["script_path"]
        if not script_path:
            raise ExternalBackendNotConfigured(
                "ProGen2 generation needs either `generation.extra.command` or `generation.extra.script_path`."
            )
        return [
            placeholders["python_bin"],
            script_path,
            "--prompt",
            placeholders["prompt"],
            "--output_dir",
            placeholders["output_dir"],
            "--num_return_sequences",
            placeholders["population_size"],
            "--max_length",
            placeholders["target_length"],
            "--seed",
            placeholders["seed"],
        ]

    def _run_command(self, command: List[str]) -> None:
        result = subprocess.run(
            command,
            cwd=ensure_path(self.config.work_dir or self.config.extra.get("cwd")),
            text=True,
            capture_output=True,
            env=_merge_env(self.config),
        )
        if result.returncode != 0:
            raise ExternalBackendExecutionError(
                f"ProGen2 command failed with exit code {result.returncode}.\nSTDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
            )

    def _parse_sequences(self, path: Path) -> List[str]:
        if path.suffix.lower() in {".fa", ".fasta"}:
            return _read_fasta_sequences(path)
        if path.suffix.lower() == ".json":
            payload = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(payload, list):
                parsed = []
                for item in payload:
                    if isinstance(item, str):
                        parsed.append(item)
                    elif isinstance(item, dict) and item.get("sequence"):
                        parsed.append(str(item["sequence"]))
                return parsed
        return []


class ExternalProteinMPNNAdapter(SequenceRefinementBackend):
    """Run a real ProteinMPNN-compatible command line and parse generated FASTA files."""

    def refine(self, request: RefinementRequest) -> List[DesignCandidate]:
        reference_structure = self._resolve_reference_structure(request)
        run_dir = Path(tempfile.mkdtemp(prefix=f"proteinmpnn_iter_{request.iteration}_"))
        placeholders = {
            "reference_structure_path": reference_structure,
            "output_dir": str(run_dir),
            "population_size": str(request.population_size),
            "sampling_temp": str(self.config.extra.get("sampling_temp", 0.1)),
            "batch_size": str(self.config.extra.get("batch_size", 1)),
            "device": str(self.config.extra.get("device", "cpu")),
            "script_path": str(self.config.extra.get("script_path", "")),
            "python_bin": str(self.config.extra.get("python_bin", "python")),
            "executable": str(self.config.executable or ""),
            "iteration": str(request.iteration),
            "seed": str(request.seed),
        }
        command = self._build_command(placeholders)
        self._run_command(command)

        fasta_candidates = list(run_dir.glob("seqs/*.fa")) + list(run_dir.glob("*.fa"))
        if not fasta_candidates:
            raise ExternalBackendExecutionError(
                f"ProteinMPNN command completed but no FASTA output was found under {run_dir}"
            )
        sequences = _read_fasta_sequences(fasta_candidates[0])
        if not sequences:
            raise ExternalBackendExecutionError(f"No sequences could be parsed from {fasta_candidates[0]}")

        parents = list(request.parents)
        candidates: List[DesignCandidate] = []
        for idx, sequence in enumerate(sequences[: request.population_size]):
            parent = parents[idx % len(parents)].sequence if parents else None
            candidates.append(
                DesignCandidate(
                    sequence=sequence,
                    origin="proteinmpnn-cli",
                    iteration=request.iteration,
                    parent=parent,
                    notes=[f"Refined by external ProteinMPNN command: {' '.join(command)}"],
                    metadata={
                        "backend": self.name,
                        "provider": self.config.provider,
                        "reference_structure_path": reference_structure,
                        "output_dir": str(run_dir),
                    },
                )
            )
        return candidates

    def _resolve_reference_structure(self, request: RefinementRequest) -> str:
        path = (
            request.constraints.reference_structure_path
            or self.config.extra.get("reference_structure_path")
            or self.config.checkpoint
        )
        if not path:
            raise ExternalBackendNotConfigured(
                "ProteinMPNN refinement requires a reference backbone structure. Provide "
                "`--reference-structure`, set constraints.reference_structure_path, or configure "
                "`refinement.extra.reference_structure_path`."
            )
        resolved = ensure_path(path)
        if resolved is None or not Path(resolved).exists():
            raise FileNotFoundError(f"Reference structure not found: {path}")
        return resolved

    def _build_command(self, placeholders: Dict[str, str]) -> List[str]:
        template = self.config.extra.get("command")
        if template:
            return _render_command(template, placeholders)

        script_path = placeholders["script_path"]
        if not script_path:
            raise ExternalBackendNotConfigured(
                "ProteinMPNN command layer needs either `refinement.extra.command` or "
                "`refinement.extra.script_path`."
            )
        command = [
            placeholders["python_bin"],
            script_path,
            "--pdb_path",
            placeholders["reference_structure_path"],
            "--out_folder",
            placeholders["output_dir"],
            "--num_seq_per_target",
            placeholders["population_size"],
            "--sampling_temp",
            placeholders["sampling_temp"],
            "--batch_size",
            placeholders["batch_size"],
        ]
        if placeholders["device"]:
            command.extend(["--device", placeholders["device"]])
        return command

    def _run_command(self, command: List[str]) -> None:
        result = subprocess.run(
            command,
            cwd=self._work_dir(),
            text=True,
            capture_output=True,
            env=self._environment(),
        )
        if result.returncode != 0:
            raise ExternalBackendExecutionError(
                f"ProteinMPNN command failed with exit code {result.returncode}.\n"
                f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
            )

    def _environment(self) -> Dict[str, str]:
        return _merge_env(self.config)

    def _work_dir(self) -> str | None:
        return ensure_path(self.config.work_dir or self.config.extra.get("cwd"))


class ExternalAlphaFold2Adapter(StructurePredictionBackend):
    """Run AlphaFold2 or ColabFold from the command line and parse prediction artifacts."""

    def predict(self, request: StructurePredictionRequest) -> StructureEvaluation:
        run_dir = Path(tempfile.mkdtemp(prefix=f"structure_iter_{request.iteration}_"))
        fasta_path = run_dir / "target.fasta"
        fasta_path.write_text(f">target\n{request.candidate.sequence}\n", encoding="utf-8")

        placeholders = {
            "input_fasta": str(fasta_path),
            "output_dir": str(run_dir),
            "sequence_name": "target",
            "sequence": request.candidate.sequence,
            "model_preset": str(self.config.extra.get("model_preset", "monomer_ptm")),
            "max_template_date": str(self.config.extra.get("max_template_date", "2020-05-14")),
            "db_preset": str(self.config.extra.get("db_preset", "full_dbs")),
            "data_dir": str(self.config.extra.get("data_dir", "")),
            "script_path": str(self.config.extra.get("script_path", "")),
            "python_bin": str(self.config.extra.get("python_bin", "python")),
            "executable": str(self.config.executable or ""),
            "iteration": str(request.iteration),
        }
        command = self._build_command(placeholders)
        self._run_command(command)
        return self._parse_outputs(run_dir, command)

    def _build_command(self, placeholders: Dict[str, str]) -> List[str]:
        template = self.config.extra.get("command")
        if template:
            return _render_command(template, placeholders)

        engine = str(self.config.extra.get("engine", "colabfold_batch")).lower()
        if engine == "colabfold_batch":
            executable = self.config.executable or self.config.extra.get("colabfold_bin") or "colabfold_batch"
            command = [str(executable), placeholders["input_fasta"], placeholders["output_dir"]]
            if self.config.extra.get("model_type"):
                command.extend(["--model-type", str(self.config.extra["model_type"])])
            if self.config.extra.get("num_recycle"):
                command.extend(["--num-recycle", str(self.config.extra["num_recycle"])])
            return command

        script_path = placeholders["script_path"]
        if not script_path:
            raise ExternalBackendNotConfigured(
                "AlphaFold2 command layer needs either `structure.extra.command` or "
                "`structure.extra.script_path`."
            )
        command = [
            placeholders["python_bin"],
            script_path,
            f"--fasta_paths={placeholders['input_fasta']}",
            f"--output_dir={placeholders['output_dir']}",
            f"--model_preset={placeholders['model_preset']}",
            f"--max_template_date={placeholders['max_template_date']}",
        ]
        if placeholders["db_preset"]:
            command.append(f"--db_preset={placeholders['db_preset']}")
        if placeholders["data_dir"]:
            command.append(f"--data_dir={placeholders['data_dir']}")
        return command

    def _run_command(self, command: List[str]) -> None:
        result = subprocess.run(
            command,
            cwd=self._work_dir(),
            text=True,
            capture_output=True,
            env=self._environment(),
        )
        if result.returncode != 0:
            raise ExternalBackendExecutionError(
                f"Structure prediction command failed with exit code {result.returncode}.\n"
                f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
            )

    def _parse_outputs(self, run_dir: Path, command: List[str]) -> StructureEvaluation:
        pdb_path = _find_first_existing(
            list(run_dir.glob("*_unrelaxed_rank_001*.pdb"))
            + list(run_dir.glob("*_relaxed_rank_001*.pdb"))
            + list(run_dir.glob("*_unrelaxed_rank_1*.pdb"))
            + list(run_dir.glob("*.pdb"))
        )
        ranking_path = _find_first_existing(list(run_dir.glob("ranking_debug.json")))
        score_json = _find_first_existing(list(run_dir.glob("*scores*.json")) + list(run_dir.glob("*.json")))

        confidence = 0.0
        ptm = 0.0
        iptm = 0.0
        rmsd_hint = 10.0
        notes = [f"Predicted by external structure command: {' '.join(command)}"]
        artifacts = {"run_dir": str(run_dir)}
        if pdb_path:
            artifacts["pdb_path"] = str(pdb_path)
            structure_stats = _extract_pdb_features(pdb_path)
            confidence = max(confidence, structure_stats.get("mean_bfactor_confidence", 0.0))
            rmsd_hint = min(rmsd_hint, structure_stats.get("compactness_hint", rmsd_hint))
            artifacts.update({k: str(v) for k, v in structure_stats.items()})
        if ranking_path:
            artifacts["ranking_debug"] = str(ranking_path)
            ranking = json.loads(ranking_path.read_text(encoding="utf-8"))
            confidence = _ranking_confidence(ranking)
            notes.append("Confidence parsed from ranking_debug.json")
        if score_json and score_json.name != "ranking_debug.json":
            artifacts["score_json"] = str(score_json)
            metrics = _extract_structure_metrics(score_json)
            confidence = metrics.get("confidence", confidence)
            ptm = metrics.get("ptm", ptm)
            iptm = metrics.get("iptm", iptm)
            rmsd_hint = metrics.get("rmsd_hint", rmsd_hint)
            notes.append(f"Metrics parsed from {score_json.name}")
        if ptm == 0.0 and confidence:
            ptm = max(0.0, confidence - 0.03)
        if iptm == 0.0 and confidence:
            iptm = max(0.0, confidence - 0.06)
        if rmsd_hint == 10.0 and confidence:
            rmsd_hint = max(0.5, 8.0 - confidence * 6.0)

        return StructureEvaluation(
            source=str(self.config.extra.get("engine", "alphafold2")),
            confidence=round(confidence, 4),
            ptm=round(ptm, 4),
            iptm=round(iptm, 4),
            rmsd_hint=round(rmsd_hint, 4),
            notes=notes,
            artifacts=artifacts,
        )

    def _environment(self) -> Dict[str, str]:
        return _merge_env(self.config)

    def _work_dir(self) -> str | None:
        return ensure_path(self.config.work_dir or self.config.extra.get("cwd"))


def _render_command(template: Iterable[str] | str, placeholders: Dict[str, str]) -> List[str]:
    if isinstance(template, str):
        return [template.format_map(_SafeFormatDict(placeholders))]
    return [str(part).format_map(_SafeFormatDict(placeholders)) for part in template]


def _read_fasta_sequences(path: Path) -> List[str]:
    sequences: List[str] = []
    current: List[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line:
            continue
        if line.startswith(">"):
            if current:
                sequences.append("".join(current))
                current = []
            continue
        current.append(line.strip())
    if current:
        sequences.append("".join(current))
    return sequences


def _find_first_existing(paths: List[Path]) -> Path | None:
    for path in paths:
        if path.exists():
            return path
    return None


def _ranking_confidence(payload: Dict[str, object]) -> float:
    for key in ("iptm+ptm", "plddts", "ptm"):
        value = payload.get(key)
        if isinstance(value, dict) and value:
            first = next(iter(value.values()))
            if isinstance(first, (int, float)):
                return float(first)
        if isinstance(value, list) and value:
            first = value[0]
            if isinstance(first, (int, float)):
                return float(first)
        if isinstance(value, (int, float)):
            return float(value)
    return 0.0


def _extract_structure_metrics(path: Path) -> Dict[str, float]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    result: Dict[str, float] = {}
    if isinstance(payload.get("plddt"), list) and payload["plddt"]:
        values = [float(v) for v in payload["plddt"]]
        result["confidence"] = sum(values) / len(values) / 100.0
    if isinstance(payload.get("mean_plddt"), (int, float)):
        result["confidence"] = float(payload["mean_plddt"]) / 100.0
    if isinstance(payload.get("ptm"), (int, float)):
        result["ptm"] = float(payload["ptm"])
    if isinstance(payload.get("iptm"), (int, float)):
        result["iptm"] = float(payload["iptm"])
    if isinstance(payload.get("rmsd"), (int, float)):
        result["rmsd_hint"] = float(payload["rmsd"])
    return result


class _SafeFormatDict(dict):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def ensure_path(path: str | None) -> str | None:
    if path is None or path == "":
        return None
    return str(Path(path).expanduser().resolve())


def _merge_env(config) -> Dict[str, str]:
    env = os.environ.copy()
    env.update({str(k): str(v) for k, v in config.extra.get("env", {}).items()})
    return env


def _extract_pdb_features(path: Path) -> Dict[str, float]:
    coords = []
    b_factors = []
    helices = 0
    sheets = 0
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith("ATOM") and line[12:16].strip() == "CA":
            try:
                x = float(line[30:38].strip())
                y = float(line[38:46].strip())
                z = float(line[46:54].strip())
                b = float(line[60:66].strip())
                coords.append((x, y, z))
                b_factors.append(b)
            except ValueError:
                continue
        elif line.startswith("HELIX"):
            helices += 1
        elif line.startswith("SHEET"):
            sheets += 1
    if not coords:
        return {}
    xs, ys, zs = zip(*coords)
    span = ((max(xs) - min(xs)) + (max(ys) - min(ys)) + (max(zs) - min(zs))) / 3.0
    mean_b = sum(b_factors) / len(b_factors) if b_factors else 0.0
    confidence = max(0.0, min(1.0, mean_b / 100.0))
    compactness_hint = max(0.5, min(12.0, span / max(len(coords), 1) * 25.0))
    return {
        "ca_count": float(len(coords)),
        "mean_bfactor_confidence": round(confidence, 4),
        "compactness_hint": round(compactness_hint, 4),
        "helix_records": float(helices),
        "sheet_records": float(sheets),
    }
