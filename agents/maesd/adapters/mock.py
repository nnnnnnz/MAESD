from __future__ import annotations

import random
from typing import List, Sequence

from ..knowledge import AMINO_ACIDS
from ..schema import DesignCandidate, StructureEvaluation
from .base import (
    GenerationRequest,
    RefinementRequest,
    SequenceGenerationBackend,
    SequenceRefinementBackend,
    StructurePredictionBackend,
    StructurePredictionRequest,
)


class MockProGen2Adapter(SequenceGenerationBackend):
    def generate(self, request: GenerationRequest) -> List[DesignCandidate]:
        rng = random.Random(request.seed)
        return [
            DesignCandidate(
                sequence=_seeded_sequence(rng, request.constraints),
                origin="mock-progen2",
                iteration=0,
                notes=["Generated by mock ProGen2 backend."],
                metadata={"backend": self.name, "provider": self.config.provider},
            )
            for _ in range(request.population_size)
        ]


class MockProteinMPNNAdapter(SequenceRefinementBackend):
    def refine(self, request: RefinementRequest) -> List[DesignCandidate]:
        rng = random.Random(request.seed + request.iteration)
        if not request.parents:
            generator = MockProGen2Adapter(self.config)
            return generator.generate(
                GenerationRequest(
                    constraints=request.constraints,
                    population_size=request.population_size,
                    seed=request.seed,
                )
            )

        children: List[DesignCandidate] = []
        while len(children) < request.population_size:
            parent = rng.choice(list(request.parents))
            mutated = _mutate_sequence(rng, parent.sequence, request.constraints)
            children.append(
                DesignCandidate(
                    sequence=mutated,
                    origin="mock-proteinmpnn",
                    iteration=request.iteration,
                    parent=parent.sequence,
                    notes=["Structure-guided refinement from mock ProteinMPNN backend."],
                    metadata={"backend": self.name, "provider": self.config.provider},
                )
            )
        return children


class MockAlphaFold2Adapter(StructurePredictionBackend):
    def predict(self, request: StructurePredictionRequest) -> StructureEvaluation:
        sequence = request.candidate.sequence
        hydrophobic_ratio = sum(aa in "AILMFWVY" for aa in sequence) / len(sequence)
        gly_pro_ratio = sum(aa in "GP" for aa in sequence) / len(sequence)
        motif_bonus = 0.08 if request.constraints.motifs else 0.0
        confidence = max(0.35, min(0.95, 0.78 + hydrophobic_ratio * 0.12 - gly_pro_ratio * 0.2 + motif_bonus))
        ptm = max(0.25, min(0.95, confidence - 0.03))
        iptm = max(0.20, min(0.95, confidence - 0.06))
        rmsd_hint = max(0.4, 8.5 - confidence * 6.0)
        return StructureEvaluation(
            source="mock-alphafold2",
            confidence=round(confidence, 4),
            ptm=round(ptm, 4),
            iptm=round(iptm, 4),
            rmsd_hint=round(rmsd_hint, 4),
            notes=["Mock structural evaluation for dry-run workflows."],
            artifacts={},
        )


def _seeded_sequence(rng: random.Random, constraints) -> str:
    length = constraints.target_length
    sequence = [rng.choice(AMINO_ACIDS) for _ in range(length)]

    if "thermostability" in constraints.optimization_goals:
        for idx in range(0, length, 7):
            sequence[idx] = rng.choice("AILVFY")
    if "salt_tolerance" in constraints.optimization_goals:
        for idx in range(3, length, 9):
            sequence[idx] = rng.choice("DEKR")
    if any("transmembrane" in domain.name for domain in constraints.domains):
        helix = "LAILVVVGIIGAIL"
        start = min(20, max(0, length // 3))
        sequence[start : start + len(helix)] = list(helix[: max(0, min(len(helix), length - start))])

    for motif in constraints.motifs:
        _insert_motif(rng, sequence, motif)

    return "".join(sequence)


def _mutate_sequence(rng: random.Random, sequence: str, constraints) -> str:
    sequence_chars = list(sequence)
    mutation_count = max(1, len(sequence_chars) // 25)
    protected = _protected_positions(sequence, constraints.motifs)

    for _ in range(mutation_count):
        idx = rng.randrange(len(sequence_chars))
        if idx in protected:
            continue
        sequence_chars[idx] = _goal_aware_residue(rng, constraints)

    for motif in constraints.motifs:
        _insert_motif(rng, sequence_chars, motif)

    return "".join(sequence_chars)


def _insert_motif(rng: random.Random, sequence: List[str], motif: str) -> None:
    if len(sequence) <= len(motif):
        return
    motif_pattern = motif.replace("X", "")
    if motif_pattern and motif_pattern in "".join(sequence):
        return
    start = rng.randint(0, len(sequence) - len(motif))
    for offset, residue in enumerate(motif):
        if residue != "X":
            sequence[start + offset] = residue


def _protected_positions(sequence: str, motifs: Sequence[str]) -> set[int]:
    protected: set[int] = set()
    for motif in motifs:
        literal = motif.replace("X", "")
        if not literal:
            continue
        match = sequence.find(literal)
        if match >= 0:
            protected.update(range(match, match + len(literal)))
    return protected


def _goal_aware_residue(rng: random.Random, constraints) -> str:
    if "thermostability" in constraints.optimization_goals:
        return rng.choice("AEILKRVY")
    if "salt_tolerance" in constraints.optimization_goals:
        return rng.choice("DEKRNQST")
    if "binding_affinity" in constraints.optimization_goals:
        return rng.choice("RHKYSTW")
    return rng.choice(AMINO_ACIDS)
